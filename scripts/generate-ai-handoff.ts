import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Scripts = Record<string, string>;

function git(args: string[], fallback = "") {
  try {
    return execFileSync("git", args, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trimEnd();
  } catch {
    return fallback;
  }
}

function parseJsonObject(value: string) {
  try {
    const parsed = JSON.parse(value);
    return parsed && typeof parsed === "object" ? parsed as Record<string, unknown> : {};
  } catch {
    return {};
  }
}

function readCurrentScripts(): Scripts {
  if (!existsSync("package.json")) return {};
  const parsed = parseJsonObject(readFileSync("package.json", "utf8"));
  const scripts = parsed.scripts;
  return scripts && typeof scripts === "object" ? scripts as Scripts : {};
}

function readHeadScripts(): Scripts {
  const raw = git(["show", "HEAD:package.json"]);
  if (!raw) return {};
  const parsed = parseJsonObject(raw);
  const scripts = parsed.scripts;
  return scripts && typeof scripts === "object" ? scripts as Scripts : {};
}

function scriptChanges(before: Scripts, after: Scripts) {
  const keys = [...new Set([...Object.keys(before), ...Object.keys(after)])].sort();
  return keys.flatMap((key) => {
    if (!(key in before) && key in after) return [`- Added \`${key}\`: \`${after[key]}\``];
    if (key in before && !(key in after)) return [`- Removed \`${key}\``];
    if (before[key] !== after[key]) return [`- Changed \`${key}\`: \`${before[key]}\` -> \`${after[key]}\``];
    return [];
  });
}

function statusPath(line: string) {
  const rawPath = line.slice(3).trim();
  const renameIndex = rawPath.indexOf(" -> ");
  return renameIndex >= 0 ? rawPath.slice(renameIndex + 4) : rawPath;
}

function bulletList(items: string[], emptyText = "- None") {
  return items.length > 0 ? items.map((item) => `- ${item}`) : [emptyText];
}

function stripGeneratedSnapshot(value: string) {
  return value.split(/\n---\n\n## Generated Repository Snapshot\n/)[0].trimEnd();
}

const status = git(["status", "--short", "--untracked-files=all"]);
const statusLines = status ? status.split(/\r?\n/).filter(Boolean) : [];
const changedFiles = statusLines.map(statusPath).sort();
const migrationFiles = statusLines
  .map(statusPath)
  .filter((file) => file.startsWith("prisma/migrations/"))
  .sort();

const branch = git(["branch", "--show-current"]) || `detached@${git(["rev-parse", "--short", "HEAD"], "unknown")}`;
const commit = git(["log", "-1", "--pretty=format:%h %s (%ci)"], "unknown");
const generatedDate = new Date().toISOString().slice(0, 10);
const packageScriptChanges = scriptChanges(readHeadScripts(), readCurrentScripts());
const handoffPath = join("docs", "AI_HANDOFF.md");
const maintainedHandoff = existsSync(handoffPath)
  ? stripGeneratedSnapshot(readFileSync(handoffPath, "utf8"))
  : "";

const generatedSnapshot = [
  "## Generated Repository Snapshot",
  "",
  `Generated by \`npm run ai:handoff\` on ${generatedDate}.`,
  "",
  "### Changed files",
  "",
  ...bulletList(changedFiles),
  "",
  "### Package.json script changes",
  "",
  ...(packageScriptChanges.length > 0 ? packageScriptChanges : ["- None detected against HEAD"]),
  "",
  "### Prisma migration files",
  "",
  ...bulletList(migrationFiles),
  "",
  "### Git status summary",
  "",
  ...(statusLines.length > 0 ? statusLines.map((line) => `- \`${line}\``) : ["- Clean worktree"]),
  "",
].join("\n");

const templateOutput = [
  "# AI Handoff",
  "",
  `Generated by \`npm run ai:handoff\` on ${generatedDate}. Review and edit before treating this as final.`,
  "",
  "## Date",
  "",
  generatedDate,
  "",
  "## Branch",
  "",
  branch,
  "",
  "## Commit",
  "",
  commit,
  "",
  "## Task implemented",
  "",
  "- TODO: Describe the task implemented.",
  "",
  "## What changed",
  "",
  "- TODO: Summarize the implementation.",
  "",
  "### Changed files",
  "",
  ...bulletList(changedFiles),
  "",
  "### Package.json script changes",
  "",
  ...(packageScriptChanges.length > 0 ? packageScriptChanges : ["- None detected against HEAD"]),
  "",
  "### Prisma migration files",
  "",
  ...bulletList(migrationFiles),
  "",
  "## Behavior added",
  "",
  "- TODO: Describe user-visible, agent-visible, or internal behavior added.",
  "",
  "## Verification results",
  "",
  "- `npx tsc --noEmit`: TODO",
  "- `npm run build`: TODO",
  "",
  "## Failed/skipped checks",
  "",
  "- TODO: List failed or skipped checks, or write `None`.",
  "",
  "## Caveats",
  "",
  "### Git status summary",
  "",
  ...(statusLines.length > 0 ? statusLines.map((line) => `- \`${line}\``) : ["- Clean worktree"]),
  "",
  "### Notes",
  "",
  "- TODO: List caveats, dirty-worktree context, or risky assumptions.",
  "",
  "## Product questions",
  "",
  "- TODO: List open product questions, or write `None`.",
  "",
  "## Recommended next step",
  "",
  "- TODO: Name the single most useful next action.",
  "",
].join("\n");

const output = maintainedHandoff
  ? [maintainedHandoff, "", "---", "", generatedSnapshot].join("\n")
  : templateOutput;

if (process.argv.includes("--write")) {
  writeFileSync(handoffPath, output, "utf8");
  console.log(`Wrote ${handoffPath}`);
} else {
  console.log(output);
}
