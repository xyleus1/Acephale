import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const migrationsDirectory = join(process.cwd(), "prisma", "migrations");
const outputPath = join(process.cwd(), "src", "lib", "migration-manifest.ts");

async function main() {
  const directories = await readdir(migrationsDirectory, { withFileTypes: true });
  const migrations = (
    await Promise.all(
      directories
        .filter((entry) => entry.isDirectory())
        .map(async (entry) => {
          try {
            await readFile(join(migrationsDirectory, entry.name, "migration.sql"));
            return entry.name;
          } catch {
            return null;
          }
        }),
    )
  ).filter((name): name is string => name !== null).sort();

  await writeFile(
    outputPath,
    `// Generated by npm run migrations:manifest. Do not edit by hand.\nexport const COMMITTED_MIGRATIONS: readonly string[] = ${JSON.stringify(migrations, null, 2)};\n`,
  );
}

void main();
