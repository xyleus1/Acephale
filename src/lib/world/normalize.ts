function stripDiacritics(value: string) {
  return value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "");
}

export function normalizeCompanyName(name: string) {
  const normalized = stripDiacritics(name)
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
  let tokens = normalized.split(" ").filter(Boolean);
  const suffixes = LEGAL_FORM_SUFFIXES
    .map((suffix) => stripDiacritics(suffix).toLowerCase().split(/\s+/))
    .sort((left, right) => right.length - left.length);
  let changed = true;
  while (changed && tokens.length) {
    changed = false;
    for (const suffix of suffixes) {
      const atStart = suffix.every((token, index) => tokens[index] === token);
      const endIndex = tokens.length - suffix.length;
      const atEnd = endIndex >= 0 && suffix.every((token, index) => tokens[endIndex + index] === token);
      if (atStart) {
        tokens = tokens.slice(suffix.length);
        changed = true;
        break;
      }
      if (atEnd) {
        tokens = tokens.slice(0, endIndex);
        changed = true;
        break;
      }
    }
  }
  return tokens.join(" ") || normalized;
}

export function normalizeDomain(value: string | null | undefined) {
  const input = value?.trim();
  if (!input) return null;
  const domain = registrableDomain(input);
  if (!domain || !domain.includes(".") || !/^[a-z0-9.-]+$/i.test(domain)) return null;
  return domain.toLowerCase();
}

export function normalizeCountry(value: string | null | undefined) {
  const input = value?.trim();
  if (!input) return null;
  const normalized = stripDiacritics(input).toLowerCase().replace(/\s+/g, " ");
  if (/^[a-z]{2}$/i.test(input)) return input.toUpperCase();
  if (/^[a-z]{3}$/i.test(input)) return COUNTRY_ALPHA_3[normalized] ?? null;
  return COUNTRY_ALIASES[normalized] ?? COUNTRY_NAMES[normalized] ?? null;
}
