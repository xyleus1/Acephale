"""Causal replay: prediction happens before an actor emits the next batch."""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass

from acephale.schemas import Event, PrefixView, Trajectory


@dataclass(frozen=True)
class DecisionPoint:
    prefix: PrefixView
    targets: tuple[Event, ...]

    def __iter__(self):
        yield self.prefix
        yield self.targets


def public_prefix(trajectory: Trajectory, before_index: int) -> PrefixView:
    events = trajectory.events[:before_index]
    tools = trajectory.initial_tools
    for event in events:
        if event.tools is not None:
            tools = event.tools
    return PrefixView(
        trajectory_id=trajectory.trajectory_id,
        benchmark=trajectory.benchmark,
        domain=trajectory.domain,
        task_id=trajectory.task_id,
        trial=trajectory.trial,
        through_seq=events[-1].seq if events else -1,
        policy=trajectory.policy,
        tools=tools,
        events=events,
    ).model_copy(deep=True)


def decision_points(trajectory: Trajectory) -> Iterator[DecisionPoint]:
    """One point per actor tool batch, with sibling requests withheld together.

    Any assistant prose immediately preceding a tool batch was generated by
    the same decision and is withheld too. A prefix cannot contain unresolved
    authoritative calls. Reordered completion events remain recorded as-is.
    """
    events = trajectory.events
    index = 0
    pending: set[str] = set()
    seen_batches: set[str] = set()
    while index < len(events):
        event = events[index]
        if event.kind == "tool_result":
            pending.discard(event.call_id)
        if event.kind != "tool_request":
            index += 1
            continue
        if pending:
            raise ValueError("New actor decision while authoritative calls are unresolved")
        end = index + 1
        batch = event.batch_id
        if batch:
            if batch in seen_batches:
                raise ValueError("A tool batch must be contiguous")
            seen_batches.add(batch)
            while end < len(events) and events[end].kind == "tool_request" and events[end].batch_id == batch:
                end += 1
        elif end < len(events) and events[end].kind == "tool_request":
            raise ValueError("Concurrent tool requests require a batch_id")
        boundary = index
        while boundary and events[boundary - 1].kind == "message" and events[boundary - 1].role == "assistant":
            boundary -= 1
        targets = events[index:end]
        prefix = public_prefix(trajectory, boundary)
        # A native actor may request an invalid or unavailable tool. Preserve that
        # error as a prediction miss; never add its name to the visible catalog.
        yield DecisionPoint(prefix, targets)
        pending.update(target.call_id for target in targets)
        index = end


def initial_prefix(trajectory: Trajectory) -> PrefixView:
    """Initial request and public policy only, before the actor's first response."""
    seen_request = False
    for index, event in enumerate(trajectory.events):
        if event.kind == "message" and event.role == "user":
            seen_request = True
        if seen_request and ((event.kind == "message" and event.role == "assistant") or event.kind == "tool_request"):
            return public_prefix(trajectory, index)
        if event.kind == "tool_request":
            # Tasks without a visible user request must not gain one from the future.
            return public_prefix(trajectory, index)
    return public_prefix(trajectory, len(trajectory.events))
